namespace PDFjet.NET {
/// <summary>The shape of the marker drawn at a Point.</summary>
public enum Shape {
    /// <summary>No marker.</summary>
    INVISIBLE,
    /// <summary>A circle.</summary>
    CIRCLE,
    /// <summary>A diamond.</summary>
    DIAMOND,
    /// <summary>A box.</summary>
    BOX,
    /// <summary>A plus sign.</summary>
    PLUS,
    /// <summary>A horizontal dash.</summary>
    HORIZONTAL_DASH,
    /// <summary>A vertical dash.</summary>
    VERTICAL_DASH,
    /// <summary>A multiplication sign.</summary>
    MULTIPLY,
    /// <summary>A star.</summary>
    STAR,
    /// <summary>An X mark.</summary>
    X_MARK,
    /// <summary>An arrow pointing up.</summary>
    UP_ARROW,
    /// <summary>An arrow pointing down.</summary>
    DOWN_ARROW,
    /// <summary>An arrow pointing left.</summary>
    LEFT_ARROW,
    /// <summary>An arrow pointing right.</summary>
    RIGHT_ARROW
}
}   // End of namespace PDFjet.NET
