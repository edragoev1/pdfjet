///
/// The hash functions and ciphers that decrypting a PDF needs, as Foundation
/// has no cryptography on Linux: MD5 (RFC 1321), SHA-256, SHA-384 and SHA-512
/// (FIPS 180-4), AES in CBC mode without padding (FIPS 197) and RC4.
///
enum Cryptography {
    static func md5(_ message: [UInt8]) -> [UInt8] {
        var h: [UInt32] = [0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476]
        let padded = pad(message, 64, false)
        var m = [UInt32](repeating: 0, count: 16)
        for chunk in stride(from: 0, to: padded.count, by: 64) {
            for i in 0..<16 {
                let j = chunk + 4 * i
                m[i] = UInt32(padded[j]) | UInt32(padded[j + 1]) << 8 |
                        UInt32(padded[j + 2]) << 16 | UInt32(padded[j + 3]) << 24
            }
            var a = h[0]
            var b = h[1]
            var c = h[2]
            var d = h[3]
            for i in 0..<64 {
                var f: UInt32
                var g: Int
                if i < 16 {
                    f = (b & c) | (~b & d)
                    g = i
                } else if i < 32 {
                    f = (d & b) | (~d & c)
                    g = (5 * i + 1) % 16
                } else if i < 48 {
                    f = b ^ c ^ d
                    g = (3 * i + 5) % 16
                } else {
                    f = c ^ (b | ~d)
                    g = (7 * i) % 16
                }
                f = f &+ a &+ md5K[i] &+ m[g]
                a = d
                d = c
                c = b
                b = b &+ ((f << md5Shifts[i]) | (f >> (32 - md5Shifts[i])))
            }
            h[0] = h[0] &+ a
            h[1] = h[1] &+ b
            h[2] = h[2] &+ c
            h[3] = h[3] &+ d
        }
        var digest = [UInt8]()
        for value in h {
            for i in 0..<4 {
                digest.append(UInt8(truncatingIfNeeded: value >> (8 * UInt32(i))))
            }
        }
        return digest
    }

    static func sha256(_ message: [UInt8]) -> [UInt8] {
        var h = sha256H
        let padded = pad(message, 64, true)
        var w = [UInt32](repeating: 0, count: 64)
        for chunk in stride(from: 0, to: padded.count, by: 64) {
            for i in 0..<16 {
                let j = chunk + 4 * i
                w[i] = UInt32(padded[j]) << 24 | UInt32(padded[j + 1]) << 16 |
                        UInt32(padded[j + 2]) << 8 | UInt32(padded[j + 3])
            }
            for i in 16..<64 {
                let s0 = rotate(w[i - 15], 7) ^ rotate(w[i - 15], 18) ^ (w[i - 15] >> 3)
                let s1 = rotate(w[i - 2], 17) ^ rotate(w[i - 2], 19) ^ (w[i - 2] >> 10)
                w[i] = w[i - 16] &+ s0 &+ w[i - 7] &+ s1
            }
            var a = h[0], b = h[1], c = h[2], d = h[3]
            var e = h[4], f = h[5], g = h[6], hh = h[7]
            for i in 0..<64 {
                let s1 = rotate(e, 6) ^ rotate(e, 11) ^ rotate(e, 25)
                let t1 = hh &+ s1 &+ ((e & f) ^ (~e & g)) &+ sha256K[i] &+ w[i]
                let s0 = rotate(a, 2) ^ rotate(a, 13) ^ rotate(a, 22)
                let t2 = s0 &+ ((a & b) ^ (a & c) ^ (b & c))
                hh = g
                g = f
                f = e
                e = d &+ t1
                d = c
                c = b
                b = a
                a = t1 &+ t2
            }
            h[0] = h[0] &+ a
            h[1] = h[1] &+ b
            h[2] = h[2] &+ c
            h[3] = h[3] &+ d
            h[4] = h[4] &+ e
            h[5] = h[5] &+ f
            h[6] = h[6] &+ g
            h[7] = h[7] &+ hh
        }
        var digest = [UInt8]()
        for value in h {
            for i in stride(from: 24, through: 0, by: -8) {
                digest.append(UInt8(truncatingIfNeeded: value >> UInt32(i)))
            }
        }
        return digest
    }

    static func sha384(_ message: [UInt8]) -> [UInt8] {
        return Array(sha512(message, sha384H)[0..<48])
    }

    static func sha512(_ message: [UInt8]) -> [UInt8] {
        return sha512(message, sha512H)
    }

    private static func sha512(_ message: [UInt8], _ initial: [UInt64]) -> [UInt8] {
        var h = initial
        let padded = pad(message, 128, true)
        var w = [UInt64](repeating: 0, count: 80)
        for chunk in stride(from: 0, to: padded.count, by: 128) {
            for i in 0..<16 {
                var value: UInt64 = 0
                for j in 0..<8 {
                    value = value << 8 | UInt64(padded[chunk + 8 * i + j])
                }
                w[i] = value
            }
            for i in 16..<80 {
                let s0 = rotate(w[i - 15], 1) ^ rotate(w[i - 15], 8) ^ (w[i - 15] >> 7)
                let s1 = rotate(w[i - 2], 19) ^ rotate(w[i - 2], 61) ^ (w[i - 2] >> 6)
                w[i] = w[i - 16] &+ s0 &+ w[i - 7] &+ s1
            }
            var a = h[0], b = h[1], c = h[2], d = h[3]
            var e = h[4], f = h[5], g = h[6], hh = h[7]
            for i in 0..<80 {
                let s1 = rotate(e, 14) ^ rotate(e, 18) ^ rotate(e, 41)
                let t1 = hh &+ s1 &+ ((e & f) ^ (~e & g)) &+ sha512K[i] &+ w[i]
                let s0 = rotate(a, 28) ^ rotate(a, 34) ^ rotate(a, 39)
                let t2 = s0 &+ ((a & b) ^ (a & c) ^ (b & c))
                hh = g
                g = f
                f = e
                e = d &+ t1
                d = c
                c = b
                b = a
                a = t1 &+ t2
            }
            h[0] = h[0] &+ a
            h[1] = h[1] &+ b
            h[2] = h[2] &+ c
            h[3] = h[3] &+ d
            h[4] = h[4] &+ e
            h[5] = h[5] &+ f
            h[6] = h[6] &+ g
            h[7] = h[7] &+ hh
        }
        var digest = [UInt8]()
        for value in h {
            for i in stride(from: 56, through: 0, by: -8) {
                digest.append(UInt8(truncatingIfNeeded: value >> UInt64(i)))
            }
        }
        return digest
    }

    // Pads the message with 0x80, zeros and its length in bits, to whole blocks.
    private static func pad(_ message: [UInt8], _ blockSize: Int, _ bigEndian: Bool) -> [UInt8] {
        var padded = message
        padded.append(0x80)
        let lengthSize = blockSize / 8      // 8 bytes for MD5 and SHA-256, 16 for SHA-512
        while padded.count % blockSize != blockSize - lengthSize {
            padded.append(0)
        }
        let bits = UInt64(message.count) &* 8
        var length = [UInt8](repeating: 0, count: lengthSize)
        for i in 0..<8 {
            let byte = UInt8(truncatingIfNeeded: bits >> (8 * UInt64(i)))
            if bigEndian {
                length[lengthSize - 1 - i] = byte
            } else {
                length[i] = byte
            }
        }
        padded.append(contentsOf: length)
        return padded
    }

    private static func rotate(_ x: UInt32, _ n: UInt32) -> UInt32 {
        return (x >> n) | (x << (32 - n))
    }

    private static func rotate(_ x: UInt64, _ n: UInt64) -> UInt64 {
        return (x >> n) | (x << (64 - n))
    }

    static func rc4(_ key: [UInt8], _ data: [UInt8]) -> [UInt8] {
        var s = [UInt8](repeating: 0, count: 256)
        for i in 0..<256 {
            s[i] = UInt8(i)
        }
        var j = 0
        for i in 0..<256 {
            j = (j + Int(s[i]) + Int(key[i % key.count])) & 0xff
            s.swapAt(i, j)
        }
        var result = [UInt8](repeating: 0, count: data.count)
        var i = 0
        j = 0
        for k in 0..<data.count {
            i = (i + 1) & 0xff
            j = (j + Int(s[i])) & 0xff
            s.swapAt(i, j)
            result[k] = data[k] ^ s[(Int(s[i]) + Int(s[j])) & 0xff]
        }
        return result
    }

    /// Encrypts the data, whose length is a multiple of 16, with a key of 16,
    /// 24 or 32 bytes.
    static func aesEncryptCBC(_ data: [UInt8], _ key: [UInt8], _ iv: [UInt8]) -> [UInt8] {
        let w = expandKey(key)
        let rounds = key.count / 4 + 6
        var result = [UInt8](repeating: 0, count: data.count / 16 * 16)
        var block = iv
        for offset in stride(from: 0, to: result.count, by: 16) {
            for i in 0..<16 {
                block[i] ^= data[offset + i]
            }
            encryptBlock(&block, w, rounds)
            for i in 0..<16 {
                result[offset + i] = block[i]
            }
        }
        return result
    }

    /// Decrypts the data, whose length is a multiple of 16, with a key of 16,
    /// 24 or 32 bytes.
    static func aesDecryptCBC(_ data: [UInt8], _ key: [UInt8], _ iv: [UInt8]) -> [UInt8] {
        let w = expandKey(key)
        let rounds = key.count / 4 + 6
        var result = [UInt8](repeating: 0, count: data.count / 16 * 16)
        var previous = iv
        var block = [UInt8](repeating: 0, count: 16)
        for offset in stride(from: 0, to: result.count, by: 16) {
            for i in 0..<16 {
                block[i] = data[offset + i]
            }
            decryptBlock(&block, w, rounds)
            for i in 0..<16 {
                result[offset + i] = block[i] ^ previous[i]
                previous[i] = data[offset + i]
            }
        }
        return result
    }

    private static func expandKey(_ key: [UInt8]) -> [UInt8] {
        let nk = key.count / 4
        let rounds = nk + 6
        var w = key
        var i = nk
        while w.count < 16 * (rounds + 1) {
            var t = Array(w[(w.count - 4)...])
            if i % nk == 0 {
                t = [aesSBox[Int(t[1])] ^ aesRcon[i / nk], aesSBox[Int(t[2])],
                        aesSBox[Int(t[3])], aesSBox[Int(t[0])]]
            } else if nk > 6 && i % nk == 4 {
                t = t.map { aesSBox[Int($0)] }
            }
            let base = w.count - 4 * nk
            for j in 0..<4 {
                w.append(w[base + j] ^ t[j])
            }
            i += 1
        }
        return w
    }

    private static func encryptBlock(_ s: inout [UInt8], _ w: [UInt8], _ rounds: Int) {
        for i in 0..<16 {
            s[i] ^= w[i]
        }
        for round in 1...rounds {
            for i in 0..<16 {
                s[i] = aesSBox[Int(s[i])]
            }
            (s[1], s[5], s[9], s[13]) = (s[5], s[9], s[13], s[1])
            (s[2], s[6], s[10], s[14]) = (s[10], s[14], s[2], s[6])
            (s[3], s[7], s[11], s[15]) = (s[15], s[3], s[7], s[11])
            if round < rounds {
                for c in stride(from: 0, to: 16, by: 4) {
                    let a0 = s[c], a1 = s[c + 1], a2 = s[c + 2], a3 = s[c + 3]
                    let x0 = xtime(a0), x1 = xtime(a1), x2 = xtime(a2), x3 = xtime(a3)
                    s[c] = x0 ^ x1 ^ a1 ^ a2 ^ a3
                    s[c + 1] = a0 ^ x1 ^ x2 ^ a2 ^ a3
                    s[c + 2] = a0 ^ a1 ^ x2 ^ x3 ^ a3
                    s[c + 3] = x0 ^ a0 ^ a1 ^ a2 ^ x3
                }
            }
            for i in 0..<16 {
                s[i] ^= w[16 * round + i]
            }
        }
    }

    private static func decryptBlock(_ s: inout [UInt8], _ w: [UInt8], _ rounds: Int) {
        for i in 0..<16 {
            s[i] ^= w[16 * rounds + i]
        }
        for round in stride(from: rounds - 1, through: 0, by: -1) {
            (s[1], s[5], s[9], s[13]) = (s[13], s[1], s[5], s[9])
            (s[2], s[6], s[10], s[14]) = (s[10], s[14], s[2], s[6])
            (s[3], s[7], s[11], s[15]) = (s[7], s[11], s[15], s[3])
            for i in 0..<16 {
                s[i] = aesInvSBox[Int(s[i])] ^ w[16 * round + i]
            }
            if round > 0 {
                for c in stride(from: 0, to: 16, by: 4) {
                    let a0 = Int(s[c]), a1 = Int(s[c + 1]), a2 = Int(s[c + 2]), a3 = Int(s[c + 3])
                    s[c] = aesMul14[a0] ^ aesMul11[a1] ^ aesMul13[a2] ^ aesMul9[a3]
                    s[c + 1] = aesMul9[a0] ^ aesMul14[a1] ^ aesMul11[a2] ^ aesMul13[a3]
                    s[c + 2] = aesMul13[a0] ^ aesMul9[a1] ^ aesMul14[a2] ^ aesMul11[a3]
                    s[c + 3] = aesMul11[a0] ^ aesMul13[a1] ^ aesMul9[a2] ^ aesMul14[a3]
                }
            }
        }
    }

    private static func xtime(_ x: UInt8) -> UInt8 {
        return (x << 1) ^ ((x & 0x80) != 0 ? 0x1B : 0)
    }
}

