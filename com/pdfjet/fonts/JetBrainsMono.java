package com.pdfjet;

/**
 * The JetBrains Mono fonts. Each constant is the path of a font file in the
 * .ttf.stream format; pass it to the Font constructor that takes a font path.
 */
public class JetBrainsMono {
    /** The default constructor */
    public JetBrainsMono() {
    }

    /** JetBrains Mono Bold */
    public static final String Bold             = "fonts/JetBrainsMono/JetBrainsMono-Bold.ttf.stream";
    /** JetBrains Mono Bold Italic */
    public static final String BoldItalic       = "fonts/JetBrainsMono/JetBrainsMono-BoldItalic.ttf.stream";
    /** JetBrains Mono ExtraLight */
    public static final String ExtraLight       = "fonts/JetBrainsMono/JetBrainsMono-ExtraLight.ttf.stream";
    /** JetBrains Mono ExtraLight Italic */
    public static final String ExtraLightItalic = "fonts/JetBrainsMono/JetBrainsMono-ExtraLightItalic.ttf.stream";
    /** JetBrains Mono Italic */
    public static final String Italic           = "fonts/JetBrainsMono/JetBrainsMono-Italic.ttf.stream";
    /** JetBrains Mono Light */
    public static final String Light            = "fonts/JetBrainsMono/JetBrainsMono-Light.ttf.stream";
    /** JetBrains Mono Light Italic */
    public static final String LightItalic      = "fonts/JetBrainsMono/JetBrainsMono-LightItalic.ttf.stream";
    /** JetBrains Mono Medium */
    public static final String Medium           = "fonts/JetBrainsMono/JetBrainsMono-Medium.ttf.stream";
    /** JetBrains Mono Medium Italic */
    public static final String MediumItalic     = "fonts/JetBrainsMono/JetBrainsMono-MediumItalic.ttf.stream";
    /** JetBrains Mono Regular */
    public static final String Regular          = "fonts/JetBrainsMono/JetBrainsMono-Regular.ttf.stream";
    /** JetBrains Mono SemiBold */
    public static final String SemiBold         = "fonts/JetBrainsMono/JetBrainsMono-SemiBold.ttf.stream";
    /** JetBrains Mono SemiBold Italic */
    public static final String SemiBoldItalic   = "fonts/JetBrainsMono/JetBrainsMono-SemiBoldItalic.ttf.stream";
}
