package com.pdfjet;

/**
 * The IBM Plex Sans Arabic fonts. Each constant is the path of a font file in the
 * .otf.stream format; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansArabic {
    /** The default constructor */
    public IBMPlexSansArabic() {
    }

    /** IBM Plex Sans Arabic Bold */
    public static final String Bold         = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-Bold.otf.stream";
    /** IBM Plex Sans Arabic ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-ExtraLight.otf.stream";
    /** IBM Plex Sans Arabic Light */
    public static final String Light        = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-Light.otf.stream";
    /** IBM Plex Sans Arabic Medium */
    public static final String Medium       = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-Medium.otf.stream";
    /** IBM Plex Sans Arabic Regular */
    public static final String Regular      = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-Regular.otf.stream";
    /** IBM Plex Sans Arabic SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-SemiBold.otf.stream";
    /** IBM Plex Sans Arabic Text */
    public static final String Text         = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-Text.otf.stream";
    /** IBM Plex Sans Arabic Thin */
    public static final String Thin         = "fonts/IBMPlexSansArabic/IBMPlexSansArabic-Thin.otf.stream";
}
