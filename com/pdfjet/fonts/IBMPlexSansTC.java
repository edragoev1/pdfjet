package com.pdfjet.fonts;

/**
 * The IBM Plex Sans TC fonts. Each constant is the path of a font file in the
 * TrueType (.ttf) format, embedded as a subset of the glyphs a document
 * draws; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansTC {
    private IBMPlexSansTC() {
    }

    /** IBM Plex Sans TC Bold */
    public static final String Bold         = "fonts/IBMPlexSansTC/IBMPlexSansTC-Bold.ttf";
    /** IBM Plex Sans TC ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansTC/IBMPlexSansTC-ExtraLight.ttf";
    /** IBM Plex Sans TC Light */
    public static final String Light        = "fonts/IBMPlexSansTC/IBMPlexSansTC-Light.ttf";
    /** IBM Plex Sans TC Medium */
    public static final String Medium       = "fonts/IBMPlexSansTC/IBMPlexSansTC-Medium.ttf";
    /** IBM Plex Sans TC Regular */
    public static final String Regular      = "fonts/IBMPlexSansTC/IBMPlexSansTC-Regular.ttf";
    /** IBM Plex Sans TC SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansTC/IBMPlexSansTC-SemiBold.ttf";
    /** IBM Plex Sans TC Text */
    public static final String Text         = "fonts/IBMPlexSansTC/IBMPlexSansTC-Text.ttf";
    /** IBM Plex Sans TC Thin */
    public static final String Thin         = "fonts/IBMPlexSansTC/IBMPlexSansTC-Thin.ttf";
}
