package com.pdfjet;

/**
 * The IBM Plex Sans TC fonts. Each constant is the path of a font file in the
 * .otf.stream format; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansTC {
    /** The default constructor */
    public IBMPlexSansTC() {
    }

    /** IBM Plex Sans TC Bold */
    public static final String Bold         = "fonts/IBMPlexSansTC/IBMPlexSansTC-Bold.otf.stream";
    /** IBM Plex Sans TC ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansTC/IBMPlexSansTC-ExtraLight.otf.stream";
    /** IBM Plex Sans TC Light */
    public static final String Light        = "fonts/IBMPlexSansTC/IBMPlexSansTC-Light.otf.stream";
    /** IBM Plex Sans TC Medium */
    public static final String Medium       = "fonts/IBMPlexSansTC/IBMPlexSansTC-Medium.otf.stream";
    /** IBM Plex Sans TC Regular */
    public static final String Regular      = "fonts/IBMPlexSansTC/IBMPlexSansTC-Regular.otf.stream";
    /** IBM Plex Sans TC SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansTC/IBMPlexSansTC-SemiBold.otf.stream";
    /** IBM Plex Sans TC Text */
    public static final String Text         = "fonts/IBMPlexSansTC/IBMPlexSansTC-Text.otf.stream";
    /** IBM Plex Sans TC Thin */
    public static final String Thin         = "fonts/IBMPlexSansTC/IBMPlexSansTC-Thin.otf.stream";
}
