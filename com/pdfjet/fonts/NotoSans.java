package com.pdfjet;

/**
 * The Noto Sans fonts. Each constant is the path of a font file in the
 * .ttf.stream format; pass it to the Font constructor that takes a font path.
 */
public class NotoSans {
    /** The default constructor */
    public NotoSans() {
    }

    /** Noto Sans Bold */
    public static final String Bold             = "fonts/NotoSans/NotoSans-Bold.ttf.stream";
    /** Noto Sans Bold Italic */
    public static final String BoldItalic       = "fonts/NotoSans/NotoSans-BoldItalic.ttf.stream";
    /** Noto Sans ExtraLight */
    public static final String ExtraLight       = "fonts/NotoSans/NotoSans-ExtraLight.ttf.stream";
    /** Noto Sans ExtraLight Italic */
    public static final String ExtraLightItalic = "fonts/NotoSans/NotoSans-ExtraLightItalic.ttf.stream";
    /** Noto Sans Italic */
    public static final String Italic           = "fonts/NotoSans/NotoSans-Italic.ttf.stream";
    /** Noto Sans Light */
    public static final String Light            = "fonts/NotoSans/NotoSans-Light.ttf.stream";
    /** Noto Sans Light Italic */
    public static final String LightItalic      = "fonts/NotoSans/NotoSans-LightItalic.ttf.stream";
    /** Noto Sans Medium */
    public static final String Medium           = "fonts/NotoSans/NotoSans-Medium.ttf.stream";
    /** Noto Sans Medium Italic */
    public static final String MediumItalic     = "fonts/NotoSans/NotoSans-MediumItalic.ttf.stream";
    /** Noto Sans Regular */
    public static final String Regular          = "fonts/NotoSans/NotoSans-Regular.ttf.stream";
    /** Noto Sans SemiBold */
    public static final String SemiBold         = "fonts/NotoSans/NotoSans-SemiBold.ttf.stream";
    /** Noto Sans SemiBold Italic */
    public static final String SemiBoldItalic   = "fonts/NotoSans/NotoSans-SemiBoldItalic.ttf.stream";
}
