package com.pdfjet;

/**
 * The IBM Plex Sans Thai fonts. Each constant is the path of a font file in the
 * .otf.stream format; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansThai {
    /** The default constructor */
    public IBMPlexSansThai() {
    }

    /** IBM Plex Sans Thai Bold */
    public static final String Bold         = "fonts/IBMPlexSansThai/IBMPlexSansThai-Bold.otf.stream";
    /** IBM Plex Sans Thai ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansThai/IBMPlexSansThai-ExtraLight.otf.stream";
    /** IBM Plex Sans Thai Light */
    public static final String Light        = "fonts/IBMPlexSansThai/IBMPlexSansThai-Light.otf.stream";
    /** IBM Plex Sans Thai Medium */
    public static final String Medium       = "fonts/IBMPlexSansThai/IBMPlexSansThai-Medium.otf.stream";
    /** IBM Plex Sans Thai Regular */
    public static final String Regular      = "fonts/IBMPlexSansThai/IBMPlexSansThai-Regular.otf.stream";
    /** IBM Plex Sans Thai SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansThai/IBMPlexSansThai-SemiBold.otf.stream";
    /** IBM Plex Sans Thai Text */
    public static final String Text         = "fonts/IBMPlexSansThai/IBMPlexSansThai-Text.otf.stream";
    /** IBM Plex Sans Thai Thin */
    public static final String Thin         = "fonts/IBMPlexSansThai/IBMPlexSansThai-Thin.otf.stream";
}
