package com.pdfjet;

/**
 * The IBM Plex Sans JP fonts. Each constant is the path of a font file in the
 * .otf.stream format; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansJP {
    /** The default constructor */
    public IBMPlexSansJP() {
    }

    /** IBM Plex Sans JP Bold */
    public static final String Bold         = "fonts/IBMPlexSansJP/IBMPlexSansJP-Bold.otf.stream";
    /** IBM Plex Sans JP ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansJP/IBMPlexSansJP-ExtraLight.otf.stream";
    /** IBM Plex Sans JP Light */
    public static final String Light        = "fonts/IBMPlexSansJP/IBMPlexSansJP-Light.otf.stream";
    /** IBM Plex Sans JP Medium */
    public static final String Medium       = "fonts/IBMPlexSansJP/IBMPlexSansJP-Medium.otf.stream";
    /** IBM Plex Sans JP Regular */
    public static final String Regular      = "fonts/IBMPlexSansJP/IBMPlexSansJP-Regular.otf.stream";
    /** IBM Plex Sans JP SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansJP/IBMPlexSansJP-SemiBold.otf.stream";
    /** IBM Plex Sans JP Text */
    public static final String Text         = "fonts/IBMPlexSansJP/IBMPlexSansJP-Text.otf.stream";
    /** IBM Plex Sans JP Thin */
    public static final String Thin         = "fonts/IBMPlexSansJP/IBMPlexSansJP-Thin.otf.stream";
}
