package com.pdfjet.fonts;

/**
 * The IBM Plex Sans JP fonts. Each constant is the path of a font file in the
 * TrueType (.ttf) format, embedded as a subset of the glyphs a document
 * draws; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansJP {
    private IBMPlexSansJP() {
    }

    /** IBM Plex Sans JP Bold */
    public static final String Bold         = "fonts/IBMPlexSansJP/IBMPlexSansJP-Bold.ttf";
    /** IBM Plex Sans JP ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansJP/IBMPlexSansJP-ExtraLight.ttf";
    /** IBM Plex Sans JP Light */
    public static final String Light        = "fonts/IBMPlexSansJP/IBMPlexSansJP-Light.ttf";
    /** IBM Plex Sans JP Medium */
    public static final String Medium       = "fonts/IBMPlexSansJP/IBMPlexSansJP-Medium.ttf";
    /** IBM Plex Sans JP Regular */
    public static final String Regular      = "fonts/IBMPlexSansJP/IBMPlexSansJP-Regular.ttf";
    /** IBM Plex Sans JP SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansJP/IBMPlexSansJP-SemiBold.ttf";
    /** IBM Plex Sans JP Text */
    public static final String Text         = "fonts/IBMPlexSansJP/IBMPlexSansJP-Text.ttf";
    /** IBM Plex Sans JP Thin */
    public static final String Thin         = "fonts/IBMPlexSansJP/IBMPlexSansJP-Thin.ttf";
}
