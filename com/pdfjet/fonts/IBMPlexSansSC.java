package com.pdfjet;

/**
 * The IBM Plex Sans SC fonts. Each constant is the path of a font file in the
 * .otf.stream format; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansSC {
    /** The default constructor */
    public IBMPlexSansSC() {
    }

    /** IBM Plex Sans SC Bold */
    public static final String Bold         = "fonts/IBMPlexSansSC/IBMPlexSansSC-Bold.otf.stream";
    /** IBM Plex Sans SC ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansSC/IBMPlexSansSC-ExtraLight.otf.stream";
    /** IBM Plex Sans SC Light */
    public static final String Light        = "fonts/IBMPlexSansSC/IBMPlexSansSC-Light.otf.stream";
    /** IBM Plex Sans SC Medium */
    public static final String Medium       = "fonts/IBMPlexSansSC/IBMPlexSansSC-Medium.otf.stream";
    /** IBM Plex Sans SC Regular */
    public static final String Regular      = "fonts/IBMPlexSansSC/IBMPlexSansSC-Regular.otf.stream";
    /** IBM Plex Sans SC SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansSC/IBMPlexSansSC-SemiBold.otf.stream";
    /** IBM Plex Sans SC Text */
    public static final String Text         = "fonts/IBMPlexSansSC/IBMPlexSansSC-Text.otf.stream";
    /** IBM Plex Sans SC Thin */
    public static final String Thin         = "fonts/IBMPlexSansSC/IBMPlexSansSC-Thin.otf.stream";
}
