package com.pdfjet;

/**
 * The IBM Plex Sans Hebrew fonts. Each constant is the path of a font file in the
 * .otf.stream format; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansHebrew {
    /** The default constructor */
    public IBMPlexSansHebrew() {
    }

    /** IBM Plex Sans Hebrew Bold */
    public static final String Bold         = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-Bold.otf.stream";
    /** IBM Plex Sans Hebrew ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-ExtraLight.otf.stream";
    /** IBM Plex Sans Hebrew Light */
    public static final String Light        = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-Light.otf.stream";
    /** IBM Plex Sans Hebrew Medium */
    public static final String Medium       = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-Medium.otf.stream";
    /** IBM Plex Sans Hebrew Regular */
    public static final String Regular      = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-Regular.otf.stream";
    /** IBM Plex Sans Hebrew SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-SemiBold.otf.stream";
    /** IBM Plex Sans Hebrew Text */
    public static final String Text         = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-Text.otf.stream";
    /** IBM Plex Sans Hebrew Thin */
    public static final String Thin         = "fonts/IBMPlexSansHebrew/IBMPlexSansHebrew-Thin.otf.stream";
}
