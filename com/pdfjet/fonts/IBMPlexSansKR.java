package com.pdfjet.fonts;

/**
 * The IBM Plex Sans KR fonts. Each constant is the path of a font file in the
 * TrueType (.ttf) format, embedded as a subset of the glyphs a document
 * draws; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansKR {
    private IBMPlexSansKR() {
    }

    /** IBM Plex Sans KR Bold */
    public static final String Bold         = "fonts/IBMPlexSansKR/IBMPlexSansKR-Bold.ttf";
    /** IBM Plex Sans KR ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansKR/IBMPlexSansKR-ExtraLight.ttf";
    /** IBM Plex Sans KR Light */
    public static final String Light        = "fonts/IBMPlexSansKR/IBMPlexSansKR-Light.ttf";
    /** IBM Plex Sans KR Medium */
    public static final String Medium       = "fonts/IBMPlexSansKR/IBMPlexSansKR-Medium.ttf";
    /** IBM Plex Sans KR Regular */
    public static final String Regular      = "fonts/IBMPlexSansKR/IBMPlexSansKR-Regular.ttf";
    /** IBM Plex Sans KR SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansKR/IBMPlexSansKR-SemiBold.ttf";
    /** IBM Plex Sans KR Text */
    public static final String Text         = "fonts/IBMPlexSansKR/IBMPlexSansKR-Text.ttf";
    /** IBM Plex Sans KR Thin */
    public static final String Thin         = "fonts/IBMPlexSansKR/IBMPlexSansKR-Thin.ttf";
}
