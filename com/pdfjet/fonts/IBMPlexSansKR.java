package com.pdfjet;

/**
 * The IBM Plex Sans KR fonts. Each constant is the path of a font file in the
 * .otf.stream format; pass it to the Font constructor that takes a font path.
 */
public class IBMPlexSansKR {
    /** The default constructor */
    public IBMPlexSansKR() {
    }

    /** IBM Plex Sans KR Bold */
    public static final String Bold         = "fonts/IBMPlexSansKR/IBMPlexSansKR-Bold.otf.stream";
    /** IBM Plex Sans KR ExtraLight */
    public static final String ExtraLight   = "fonts/IBMPlexSansKR/IBMPlexSansKR-ExtraLight.otf.stream";
    /** IBM Plex Sans KR Light */
    public static final String Light        = "fonts/IBMPlexSansKR/IBMPlexSansKR-Light.otf.stream";
    /** IBM Plex Sans KR Medium */
    public static final String Medium       = "fonts/IBMPlexSansKR/IBMPlexSansKR-Medium.otf.stream";
    /** IBM Plex Sans KR Regular */
    public static final String Regular      = "fonts/IBMPlexSansKR/IBMPlexSansKR-Regular.otf.stream";
    /** IBM Plex Sans KR SemiBold */
    public static final String SemiBold     = "fonts/IBMPlexSansKR/IBMPlexSansKR-SemiBold.otf.stream";
    /** IBM Plex Sans KR Text */
    public static final String Text         = "fonts/IBMPlexSansKR/IBMPlexSansKR-Text.otf.stream";
    /** IBM Plex Sans KR Thin */
    public static final String Thin         = "fonts/IBMPlexSansKR/IBMPlexSansKR-Thin.otf.stream";
}
