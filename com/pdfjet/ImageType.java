package com.pdfjet;

/**
 * Used to specify the image type of an image.
 * Supported types: ImageType.JPG, ImageType.PNG and ImageType.BMP
 * See the Image class for more information.
 */
public enum ImageType {
    /** JPEG image */
    JPG,
    /** PNG image */
    PNG,
    /** Bitmap image */
    BMP
}
