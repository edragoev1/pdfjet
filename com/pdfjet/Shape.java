package com.pdfjet;

/**
 * The shape of the marker drawn at a Point.
 */
public enum Shape {
    /** No marker. */
    INVISIBLE,
    /** A circle. */
    CIRCLE,
    /** A diamond. */
    DIAMOND,
    /** A box. */
    BOX,
    /** A plus sign. */
    PLUS,
    /** A horizontal dash. */
    HORIZONTAL_DASH,
    /** A vertical dash. */
    VERTICAL_DASH,
    /** A multiplication sign. */
    MULTIPLY,
    /** A star. */
    STAR,
    /** An X mark. */
    X_MARK,
    /** An arrow pointing up. */
    UP_ARROW,
    /** An arrow pointing down. */
    DOWN_ARROW,
    /** An arrow pointing left. */
    LEFT_ARROW,
    /** An arrow pointing right. */
    RIGHT_ARROW
}
