package com.pdfjet;

/**
 * Used to specify the text direction in TextBox.
 */
public enum Direction {
    /** The text runs from left to right. */
    LEFT_TO_RIGHT,
    /** The text runs from bottom to top. */
    BOTTOM_TO_TOP,
    /** The text runs from top to bottom. */
    TOP_TO_BOTTOM;
}
